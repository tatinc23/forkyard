// Bundles seed/ballast/ (the hand-built starting repo) into src/template/seed.generated.ts.
// Usage: node scripts/build-seed.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../seed/ballast/", import.meta.url));
const out = fileURLToPath(new URL("../src/template/seed.generated.ts", import.meta.url));
const TEXT = /\.(html|css|js|mjs|ts|json|jsonc|md|txt|svg|yml|yaml|toml)$|(^|\/)_headers$|(^|\/)_redirects$/;
const files = {};
const walk = (dir) => {
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (name === "node_modules" || name === ".DS_Store") continue;
		if (statSync(p).isDirectory()) walk(p);
		else {
			const rel = relative(root, p);
			if (TEXT.test(rel)) files[rel] = readFileSync(p, "utf8");
			else console.warn("skipping non-text file", rel);
		}
	}
};
walk(root);
const total = Object.values(files).reduce((n, c) => n + c.length, 0);
writeFileSync(out, `// Generated by scripts/build-seed.mjs from seed/ballast/. Do not edit by hand.\nexport const SEED_FILES: Record<string, string> | null = ${JSON.stringify(files, null, 1)};\n`);
console.log(`seed: ${Object.keys(files).length} files, ${(total / 1024).toFixed(1)} KB`);
