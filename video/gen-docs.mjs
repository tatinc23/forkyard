// node gen-docs.mjs : derives voline.js (VO lines with measured durations), captions_<seg>.srt and VO_SCRIPT.md from vo.json + build/tts/durations.json.
// Captions, VO script and film cannot drift: they all come from vo.json.
import fs from "node:fs";
globalThis.window = globalThis;
await import("./facts.js"); await import("./capchunk.js");
const VO = JSON.parse(fs.readFileSync("vo.json", "utf8"));
const D = fs.existsSync("build/tts/durations.json") ? JSON.parse(fs.readFileSync("build/tts/durations.json", "utf8")) : {};
const lines = VO.lines.map((l) => ({ ...l, dur: D[l.id] ? D[l.id].sec : +(l.text.split(/\s+/).length / 2.5).toFixed(2), measured: !!D[l.id] }));
fs.writeFileSync("voline.js", "// generated by gen-docs.mjs from vo.json + build/tts/durations.json. Do not edit.\nwindow.VODATA = " + JSON.stringify({ voice: VO.voice, lines }, null, 1) + ";\n");
const ts = (s) => { const ms = Math.round(s * 1000); const p = (n, w = 2) => String(n).padStart(w, "0"); return `${p(Math.floor(ms / 3600000))}:${p(Math.floor(ms / 60000) % 60)}:${p(Math.floor(ms / 1000) % 60)},${p(ms % 1000, 3)}`; };
const segDur = { open: 96, hood: 43, close: 15.6 };
for (const seg of ["open", "hood", "close"]) {
  const cues = CAPCHUNK.captionsFor(lines, seg);
  fs.writeFileSync(`captions_${seg}.srt`, cues.map(([a, b, t], i) => `${i + 1}\n${ts(a)} --> ${ts(b)}\n${t}\n`).join("\n"));
}
// in-app teaser: open + close, captions offset by the open's duration (96 s)
{ const cues = [...CAPCHUNK.captionsFor(lines, "open"), ...CAPCHUNK.captionsFor(lines, "close").map(([a, b, t]) => [a + 96, b + 96, t])];
  fs.mkdirSync("out", { recursive: true });
  fs.writeFileSync("out/master_16x9.srt", cues.map(([a, b, t], i) => `${i + 1}\n${ts(a)} --> ${ts(b)}\n${t}\n`).join("\n"));
  fs.writeFileSync("out/master_16x9.vtt", "WEBVTT\n\n" + cues.map(([a, b, t]) => `${ts(a).replace(",", ".")} --> ${ts(b).replace(",", ".")}\n${t}\n`).join("\n")); }
// ---- overlap / fit check (printed and written into VO_SCRIPT.md) ----
const issues = [];
for (const seg of ["open", "hood", "close"]) {
  const L = lines.filter((l) => l.seg === seg);
  L.forEach((l, i) => { const end = l.t + l.dur, nxt = L[i + 1] ? L[i + 1].t : segDur[seg]; if (end > nxt - 0.12) issues.push(`${l.id} ends ${end.toFixed(2)} s, next starts ${nxt.toFixed(2)} s (overrun ${(end - nxt + 0.12).toFixed(2)} s)`); });
}
const fmt = (t) => (t === undefined ? "-" : t.toFixed(1));
const wc = (s) => s.split(/\s+/).length;
const segName = { open: "A. Opening film (about 96 s)", hood: "B. Under the hood (about 43 s)", walk: "C. Product walkthrough (about 3 min; segment G times these against the app captures)", close: "D. Close (about 16 s)" };
let md = `# Forkyard demo video: voiceover script (whole video)

Generated by \`node gen-docs.mjs\` from \`vo.json\`. Edit \`vo.json\`, then run \`node tts.mjs && node gen-docs.mjs\`. Do not edit this table.

Voice: Cloudflare Workers AI text-to-speech, \`${VO.voice.model}\`, speaker \`${VO.voice.speaker}\` (calm, plain English). Order of the video: A (open) -> C (product walkthrough) -> B (under the hood) -> D (close).
Pace: measured per line below ("w/s"); the film's overall pace is about 2.3 to 2.8 words per second (140 to 165 wpm).
Numbers are spliced from \`facts.js\`; a line that would speak a null number is not allowed (tts.mjs fails).

`;
for (const seg of ["open", "walk", "hood", "close"]) {
  const L = lines.filter((l) => l.seg === seg); const words = L.reduce((n, l) => n + wc(CAPCHUNK.fill(l.text)), 0); const secs = L.reduce((n, l) => n + l.dur, 0);
  md += `## ${segName[seg]}\n\n${words} words, ${secs.toFixed(0)} s of speech${L.every((l) => l.measured) ? " (measured)" : " (estimated; run tts.mjs)"}.\n\n| Line id | Beat | Start (s) | Dur (s) | w/s | Narration |\n|---|---|---|---|---|---|\n`;
  for (const l of L) md += `| ${l.id} | ${l.beat} | ${fmt(l.t)} | ${l.dur.toFixed(1)} | ${(wc(l.text) / l.dur).toFixed(1)} | ${CAPCHUNK.fill(l.text)} |\n`;
  md += "\n";
}
md += `## Fit check (does each line end before the next starts?)\n\n${issues.length ? issues.map((x) => "- " + x).join("\n") : "All lines in A, B and D end at least 0.12 s before the next line starts."}\n`;
md += `\n## Pronunciation notes\n- x402 is spoken "x four oh two" (\`say\` field); GLM-5.3 Flash is spoken "G L M five point three Flash"; captions show the written form.\n- Section C has no start times: segment G places each line on its capture of the app (beat ids: landing, repo, goal, plan, override, approve, crew, focus, conflict, inspector, scale, exceptions, visual, revert, payouts, hall).\n`;
// Section C (the product walkthrough) is owned by segment G: if VO_SCRIPT.md already has one, keep it byte for byte.
if (fs.existsSync("VO_SCRIPT.md")) {
  const old = fs.readFileSync("VO_SCRIPT.md", "utf8"), re = /## C\. [\s\S]*?(?=\n## |$)/;
  const keep = old.match(re), mine = md.match(re);
  if (keep && mine) md = md.replace(mine[0], keep[0].replace(/\s+$/, "") + "\n");
}
fs.writeFileSync("VO_SCRIPT.md", md);
console.log(issues.length ? "OVERRUNS:\n" + issues.join("\n") : "no overruns", "\nlines:", lines.length);
